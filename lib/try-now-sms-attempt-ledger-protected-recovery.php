<?php
declare(strict_types=1);

/**
 * Smart Text Try Now - Protected-key probe recovery.
 *
 * ISOLATED PLESK CLI TESTING ONLY.
 * PHP 7.4 compatible.
 *
 * Authenticates expected checkpoint evidence using
 * protected server-side cryptographic configuration.
 *
 * Reads only through the existing restricted reader.
 *
 * No database writes, COMMIT, filesystem writes,
 * HTTP, Sendmode, automatic retry or cleanup.
 */

require_once __DIR__
    . '/try-now-sms-attempt-ledger-protected-advance-evidence.php';

require_once __DIR__
    . '/try-now-sms-attempt-ledger-probe-recovery.php';

function stTryNowProtectedRecoveryResult(
    string $status
): array {
    $result = stTryNowLedgerRecoveryResult($status);

    $result['protected_binding_verified'] = false;
    $result['independent_reader_verified'] = false;
    $result['observation_status'] = null;

    return $result;
}

/**
 * Compare an expected synthetic checkpoint against
 * a restricted, independently observed ledger row.
 *
 * The caller supplies:
 * - A restricted read-only PDO connection
 * - Synthetic reservation and journal evidence
 * - An expected authenticated head seal
 * - A reported commit signal
 * - The original writer CONNECTION_ID()
 *
 * The caller does NOT supply:
 * - HMAC keys
 * - A database row
 * - SQL or stored procedure names
 * - Permission to send or retry an SMS
 *
 * Reported commit signals are not independently
 * authenticated. Even an acknowledged, matching
 * checkpoint never authorises SMS transport.
 */
function stTryNowAssessProtectedSyntheticProbeCommit(
    PDO $reader,
    array $reservation,
    array $journalRecords,
    array $expectedSeal,
    string $commitSignal,
    int $writerConnectionId,
    bool $allowCliTest = false
): array {
    if (!stTryNowLedgerRecoveryTestAllowed(
        $allowCliTest
    )) {
        return stTryNowProtectedRecoveryResult(
            'disabled'
        );
    }

    if (!in_array($commitSignal, [
        'not_attempted',
        'acknowledged',
        'acknowledgement_lost',
        'failed_or_unknown',
    ], true)) {
        return stTryNowProtectedRecoveryResult(
            'invalid_commit_signal'
        );
    }

    if (!stTryNowLedgerRecoveryReservationValid(
        $reservation
    )) {
        return stTryNowProtectedRecoveryResult(
            'invalid_reservation'
        );
    }

    if (!stTryNowProtectedProbeSyntheticValid(
        $reservation['campaign_id'],
        $reservation['customer_id'],
        $reservation['attempt_id']
    )) {
        return stTryNowProtectedRecoveryResult(
            'invalid_synthetic_identity'
        );
    }

    if ($writerConnectionId <= 0) {
        return stTryNowProtectedRecoveryResult(
            'invalid_writer_session'
        );
    }

    /*
     * Only the fixed private keyring is trusted.
     * No key arguments enter this public interface.
     */
    $keys = stTryNowProtectedProbeLoadKeys();

    if ($keys === null) {
        return stTryNowProtectedRecoveryResult(
            'protected_keyring_unavailable'
        );
    }

    try {
        /*
         * Reconstruct the synthetic recipient binding
         * and journal slot independently.
         */
        $recipient =
            stTryNowProtectedProbeRecipientDigest(
                $reservation['attempt_id'],
                $keys['recipient']
            );

        if (!hash_equals(
            $recipient,
            $reservation['recipient_digest']
        )) {
            return stTryNowProtectedRecoveryResult(
                'recipient_binding_mismatch'
            );
        }

        $slot = stTryNowJournalSlotId(
            $keys['namespace'],
            $reservation['campaign_id'],
            $reservation['customer_id'],
            $keys['binding']
        );

        if (!hash_equals(
            $slot,
            $reservation['journal_slot_id']
        )) {
            return stTryNowProtectedRecoveryResult(
                'journal_slot_mismatch'
            );
        }

        $count = count($journalRecords);

        if (
            $count < 1 ||
            $count > 3 ||
            array_keys($journalRecords) !==
                range(0, $count - 1)
        ) {
            return stTryNowProtectedRecoveryResult(
                'invalid_expected_evidence'
            );
        }

        /*
         * A protected synthetic recovery request may
         * describe only the states generated by our
         * protected test interfaces.
         *
         * No fabricated provider_accepted or
         * provider_rejected checkpoints.
         */
        $events = array_column(
            $journalRecords,
            'event'
        );

        $allowedHistories = [
            ['prepared'],
            ['prepared', 'transport_started'],
            ['prepared', 'cancelled_before_transport'],
            [
                'prepared',
                'transport_started',
                'provider_unknown',
            ],
        ];

        if (!in_array(
            $events,
            $allowedHistories,
            true
        )) {
            return stTryNowProtectedRecoveryResult(
                'unsupported_synthetic_history'
            );
        }

        /*
         * Re-authenticate the complete expected
         * history and the supplied head seal.
         */
        $verified = stTryNowVerifyJournalHeadSeal(
            $journalRecords,
            $expectedSeal,
            $keys['record'],
            $keys['seal']
        );

        if ($verified['valid'] !== true) {
            return stTryNowProtectedRecoveryResult(
                'invalid_expected_evidence'
            );
        }

        $first = $journalRecords[0];

        if (
            $first['attempt_id'] !==
                $reservation['attempt_id'] ||
            $first['customer_id'] !==
                $reservation['customer_id'] ||
            $first['campaign_id'] !==
                $reservation['campaign_id']
        ) {
            return stTryNowProtectedRecoveryResult(
                'journal_identity_mismatch'
            );
        }

        /*
         * Independently validate the same evidence
         * against the established procedure planner.
         *
         * This does NOT execute a procedure.
         */
        $operation = $count === 1
            ? 'initialize'
            : 'advance';

        $plan = stTryNowRestrictedProcedureCallPlan(
            $operation,
            $reservation,
            $journalRecords,
            $expectedSeal,
            $keys['namespace'],
            $keys['binding'],
            $keys['record'],
            $keys['seal'],
            true
        );

        if (
            $plan['procedure_call_candidate'] !== true ||
            $plan['status'] !==
                'ready_for_restricted_procedure_test_only'
        ) {
            return stTryNowProtectedRecoveryResult(
                'invalid_expected_evidence'
            );
        }

        /*
         * The existing recovery adapter obtains
         * its own database observation.
         *
         * A caller cannot supply or forge an
         * observed row through this interface.
         */
        $assessment =
            stTryNowAssessRestrictedSyntheticProbeCommit(
                $reader,
                $reservation,
                $journalRecords,
                $expectedSeal,
                $keys['namespace'],
                $keys['binding'],
                $keys['record'],
                $keys['seal'],
                $commitSignal,
                $writerConnectionId,
                true
            );

        $status = $assessment['status'] ??
            'recovery_requires_review';

        if (!is_string($status) || $status === '') {
            return stTryNowProtectedRecoveryResult(
                'recovery_requires_review'
            );
        }

        /*
         * Return a fixed non-deliverable result.
         * No cryptographic keys or observed database
         * row are returned to the caller.
         */
        $result = stTryNowProtectedRecoveryResult(
            $status
        );

        $result['protected_binding_verified'] =
            true;

        $result['independent_reader_verified'] =
            ($assessment[
                'independent_reader_verified'
            ] ?? false) === true;

        $result['observation_status'] =
            $assessment['observation_status']
                ?? null;

        $result['fresh_checkpoint_observed'] =
            ($assessment[
                'fresh_checkpoint_observed'
            ] ?? false) === true;

        $result[
            'commit_acknowledgement_reported'
        ] = ($assessment[
            'commit_acknowledgement_reported'
        ] ?? false) === true;

        /*
         * checkpoint_committed remains false.
         *
         * This adapter is an assessment interface,
         * not a delivery authorisation interface.
         */
        return $result;

    } catch (Throwable $e) {
        return stTryNowProtectedRecoveryResult(
            'invalid_expected_evidence'
        );
    }
}
