<?php
declare(strict_types=1);

/**
 * Smart Text Try Now - Protected checkpoint evidence.
 *
 * ISOLATED PLESK CLI TESTING ONLY.
 * PHP 7.4 compatible.
 *
 * Produces authenticated synthetic journal records
 * using the private server-side keyring.
 *
 * No PDO, SQL, COMMIT, filesystem writes or SMS.
 * No caller-supplied cryptographic keys.
 *
 * provider_unknown is a SIMULATED outcome only.
 * It is not evidence of an actual Sendmode call.
 */

require_once __DIR__
    . '/try-now-sms-attempt-ledger-protected-executor.php';

/**
 * Build the next authenticated synthetic checkpoint.
 *
 * Permitted test-only transitions:
 *
 * prepared -> transport_started
 * prepared -> cancelled_before_transport
 * transport_started -> provider_unknown
 *
 * Provider acceptance/rejection is deliberately
 * not generated by this interface.
 */
function stTryNowProtectedProbeAdvanceEvidence(
    array $reservation,
    array $previousRecords,
    array $previousSeal,
    string $nextEvent,
    string $recordedAtUtc,
    bool $allowCliTest = false
): array {
    if (!stTryNowLedgerRecoveryTestAllowed(
        $allowCliTest
    )) {
        return stTryNowProtectedProbeResult(
            'disabled'
        );
    }

    if (!stTryNowLedgerRecoveryReservationValid(
        $reservation
    )) {
        return stTryNowProtectedProbeResult(
            'invalid_reservation'
        );
    }

    if (!stTryNowProtectedProbeSyntheticValid(
        $reservation['campaign_id'],
        $reservation['customer_id'],
        $reservation['attempt_id']
    )) {
        return stTryNowProtectedProbeResult(
            'invalid_synthetic_identity'
        );
    }

    $keys = stTryNowProtectedProbeLoadKeys();

    if ($keys === null) {
        return stTryNowProtectedProbeResult(
            'protected_keyring_unavailable'
        );
    }

    try {
        $expectedRecipient =
            stTryNowProtectedProbeRecipientDigest(
                $reservation['attempt_id'],
                $keys['recipient']
            );

        if (!hash_equals(
            $expectedRecipient,
            $reservation['recipient_digest']
        )) {
            return stTryNowProtectedProbeResult(
                'recipient_binding_mismatch'
            );
        }

        $expectedSlot = stTryNowJournalSlotId(
            $keys['namespace'],
            $reservation['campaign_id'],
            $reservation['customer_id'],
            $keys['binding']
        );

        if (!hash_equals(
            $expectedSlot,
            $reservation['journal_slot_id']
        )) {
            return stTryNowProtectedProbeResult(
                'journal_slot_mismatch'
            );
        }

        $count = count($previousRecords);

        if (
            ($count !== 1 && $count !== 2) ||
            array_keys($previousRecords) !==
                range(0, $count - 1)
        ) {
            return stTryNowProtectedProbeResult(
                'invalid_previous_length'
            );
        }

        /*
         * Verify the entire previous journal against
         * its authenticated checkpoint before adding
         * any new record.
         */
        $verified = stTryNowVerifyJournalHeadSeal(
            $previousRecords,
            $previousSeal,
            $keys['record'],
            $keys['seal']
        );

        if ($verified['valid'] !== true) {
            return stTryNowProtectedProbeResult(
                'invalid_previous_checkpoint'
            );
        }

        $first = $previousRecords[0];

        if (
            $first['attempt_id'] !==
                $reservation['attempt_id'] ||
            $first['campaign_id'] !==
                $reservation['campaign_id'] ||
            $first['customer_id'] !==
                $reservation['customer_id']
        ) {
            return stTryNowProtectedProbeResult(
                'journal_identity_mismatch'
            );
        }

        $last = $previousRecords[$count - 1];

        /*
         * Synthetic-only state machine.
         *
         * Never generate provider_accepted or
         * provider_rejected from caller instructions.
         */
        $allowed = [
            'prepared' => [
                'transport_started',
                'cancelled_before_transport',
            ],
            'transport_started' => [
                'provider_unknown',
            ],
        ];

        $previousEvent = $last['event'];

        if (
            ($count === 1 &&
                $previousEvent !== 'prepared') ||
            ($count === 2 &&
                $previousEvent !== 'transport_started') ||
            !in_array(
                $nextEvent,
                $allowed[$previousEvent] ?? [],
                true
            )
        ) {
            return stTryNowProtectedProbeResult(
                'invalid_checkpoint_transition'
            );
        }

        /*
         * All timestamps use canonical fixed-width
         * UTC formatting. Lexical comparison therefore
         * correctly checks ordering.
         *
         * Record creation separately validates the
         * exact timestamp format.
         */
        if (
            strcmp(
                $recordedAtUtc,
                $last['recorded_at_utc']
            ) <= 0
        ) {
            return stTryNowProtectedProbeResult(
                'nonmonotonic_timestamp'
            );
        }

        $newRecord = stTryNowBuildJournalRecord(
            $reservation['attempt_id'],
            $reservation['customer_id'],
            $reservation['campaign_id'],
            $count + 1,
            $nextEvent,
            $recordedAtUtc,
            $last['mac'],
            $keys['record']
        );

        $candidateRecords = $previousRecords;
        $candidateRecords[] = $newRecord;

        $candidateSeal =
            stTryNowBuildJournalHeadSeal(
                $candidateRecords,
                $keys['record'],
                $keys['seal']
            );

        /*
         * Independently validate the complete
         * candidate against the existing restricted
         * procedure planner.
         *
         * This does not execute its plan.
         */
        $plan = stTryNowRestrictedProcedureCallPlan(
            'advance',
            $reservation,
            $candidateRecords,
            $candidateSeal,
            $keys['namespace'],
            $keys['binding'],
            $keys['record'],
            $keys['seal'],
            true
        );

        if (
            $plan['procedure_call_candidate'] !== true ||
            $plan['status'] !==
                'ready_for_restricted_procedure_test_only' ||
            $plan['procedure'] !==
                'try_now_ledger_probe_advance' ||
            count($plan['parameters']) !== 12
        ) {
            return stTryNowProtectedProbeResult(
                'invalid_checkpoint_progression'
            );
        }

        $result = stTryNowProtectedProbeResult(
            'synthetic_checkpoint_candidate_test_only'
        );

        $result['evidence_ready'] = true;
        $result['reservation'] = $reservation;
        $result['journal_records'] =
            $candidateRecords;
        $result['head_seal'] =
            $candidateSeal;

        /*
         * Important: even valid evidence never
         * authorises transport, retry or cleanup.
         */
        return $result;

    } catch (Throwable $e) {
        return stTryNowProtectedProbeResult(
            'invalid_checkpoint_candidate'
        );
    }
}
